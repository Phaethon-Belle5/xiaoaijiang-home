import { openTab, connect, closeTab, sleep, evalJs } from './cdp-client.mjs';
const t = await openTab('about:blank');
const c = await connect(t.ws);
const ws2 = new WebSocket(t.ws);
await new Promise(r => ws2.addEventListener('open', r));
ws2.send(JSON.stringify({ id: 1, method: 'Runtime.enable' }));
await c.send('Network.enable');
await c.send('Network.setCacheDisabled', { cacheDisabled: true });
await c.send('Emulation.setDeviceMetricsOverride', { width: 1400, height: 900, deviceScaleFactor: 1, mobile: false });
await c.send('Page.navigate', { url: 'https://map.231060101.xyz/?act=' + Date.now() });
await sleep(13000);
await evalJs(c, "(function(){var l=document.getElementById('launch');if(l)l.remove();return 0})()");
await sleep(600);
await evalJs(c, "openMemPop('shelf'), 1");
await sleep(8000);
console.log('memoryShelfState 可读: ' + await evalJs(c, '(function(){try{return typeof memoryShelfState}catch(e){return "不可读: "+e.message}})()'));
console.log('active 前: ' + await evalJs(c, '(function(){try{return memoryShelfState.active}catch(e){return "?"}})()'));
await evalJs(c, 'memorySetActive(2, true), 1');
await sleep(1500);
console.log('active 后: ' + await evalJs(c, '(function(){try{return memoryShelfState.active}catch(e){return "?"}})()'));
console.log('memoryUpdateProvinceInfo: ' + await evalJs(c, 'typeof window.memoryUpdateProvinceInfo'));
console.log('手动调它: ' + await evalJs(c, '(function(){try{window.memoryUpdateProvinceInfo();return "调了"}catch(e){return "❌ "+e.message}})()'));
await sleep(1500);
console.log('调用后面板: ' + await evalJs(c, '(function(){var p=document.getElementById("memoryProvinceInfo");return p?(p.querySelector(".memory-info-name")||{}).textContent:"-"})()'));
ws2.close(); await closeTab(t.id);
