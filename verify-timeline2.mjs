import { openTab, connect, closeTab, sleep, evalJs } from './cdp-client.mjs';
const t = await openTab('about:blank');
const c = await connect(t.ws);
const ws2 = new WebSocket(t.ws);
await new Promise(r => ws2.addEventListener('open', r));
const errs=[];
ws2.addEventListener('message', ev => { try { const m = JSON.parse(ev.data);
  if(m.method==='Runtime.exceptionThrown'){const d=m.params.exceptionDetails;errs.push(String(d.exception&&d.exception.description||d.text).split('\n')[0].slice(0,140));}
} catch(e){} });
ws2.send(JSON.stringify({ id: 1, method: 'Runtime.enable' }));
await c.send('Network.enable');
await c.send('Network.setCacheDisabled', { cacheDisabled: true });
await c.send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 950, deviceScaleFactor: 1.5, mobile: false });
await c.send('Page.navigate', { url: 'https://map.231060101.xyz/?tl2=' + Date.now() });
await sleep(13000);
await evalJs(c, "(function(){var l=document.getElementById('launch');if(l)l.remove();return 0})()");
await sleep(700);
await evalJs(c, "openMemPop('time'), 1");
await sleep(5000);
console.log('面板开: ' + await evalJs(c, '(function(){var p=document.getElementById("memPanel");return p?p.classList.contains("show"):"无"})()'));
console.log('节点: ' + await evalJs(c, 'document.querySelectorAll("#memPanel .tl-node").length'));
console.log('角色 transform: ' + await evalJs(c, '(function(){var w=document.getElementById("tlWalker");return w?w.style.transform:"无"})()'));
const fs = await import('node:fs/promises');
const { data } = await c.send('Page.captureScreenshot', { format: 'png' });
await fs.writeFile('B:/dell/Documents/harness/shots/timeline-1.png', Buffer.from(data, 'base64'));
await sleep(7000);
console.log('7 秒后 transform: ' + await evalJs(c, '(function(){var w=document.getElementById("tlWalker");return w?w.style.transform:"无"})()'));
const { data: d2 } = await c.send('Page.captureScreenshot', { format: 'png' });
await fs.writeFile('B:/dell/Documents/harness/shots/timeline-2.png', Buffer.from(d2, 'base64'));
console.log('截图已存');
console.log('错误: ' + (errs.length ? errs.slice(0,2).join(' | ') : '无'));
ws2.close(); await closeTab(t.id);
