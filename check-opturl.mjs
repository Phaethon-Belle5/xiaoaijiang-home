import { openTab, connect, closeTab, sleep, evalJs } from './cdp-client.mjs';
const t = await openTab('about:blank');
const c = await connect(t.ws);
const ws2 = new WebSocket(t.ws);
await new Promise(r => ws2.addEventListener('open', r));
ws2.send(JSON.stringify({ id: 1, method: 'Runtime.enable' }));
await c.send('Network.enable');
await c.send('Emulation.setDeviceMetricsOverride', { width: 1400, height: 900, deviceScaleFactor: 1, mobile: false });
await c.send('Page.navigate', { url: 'https://map.231060101.xyz/?o=' + Date.now() });
await sleep(11000);
await evalJs(c, "(function(){var l=document.getElementById('launch');if(l)l.remove();return 0})()");
await sleep(500);
console.log('原始: ' + (await evalJs(c, 'GALLERY[0].url')).slice(0, 100));
console.log('thumbUrl: ' + (await evalJs(c, 'thumbUrl(GALLERY[0].url)')).slice(0, 110));
console.log('viewUrl : ' + (await evalJs(c, 'viewUrl(GALLERY[0].url)')).slice(0, 110));
console.log('records 里第一条 src: ' + (await evalJs(c, 'memAtlasRecords()[0].src')).slice(0, 110));
const st = await evalJs(c, `(async()=>{ const u=memAtlasRecords()[0].src; try{const r=await fetch(u,{method:'GET'});return r.status+' '+r.headers.get('content-type')}catch(e){return '❌ '+e.message} })()`);
console.log('该 src 的 HTTP: ' + st);
ws2.close(); await closeTab(t.id);
