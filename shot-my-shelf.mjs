import { openTab, connect, closeTab, sleep, evalJs } from './cdp-client.mjs';
const t = await openTab('about:blank');
const c = await connect(t.ws);
const ws2 = new WebSocket(t.ws);
await new Promise(r => ws2.addEventListener('open', r));
ws2.send(JSON.stringify({ id: 1, method: 'Runtime.enable' }));
await c.send('Network.enable');
await c.send('Network.setCacheDisabled', { cacheDisabled: true });
await c.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 2, mobile: false });
await c.send('Page.navigate', { url: 'https://map.231060101.xyz/?s=' + Date.now() });
await sleep(11000);
await evalJs(c, "(function(){var l=document.getElementById('launch');if(l)l.remove();return 1})()");
await sleep(700);
await evalJs(c, "(function(){ if(typeof openMemPop==='function')openMemPop(); return 1; })()");
await sleep(3500);
await evalJs(c, 'setMemTab("shelf"), 1');
await sleep(4500);
console.log('书数: ' + await evalJs(c, 'document.querySelectorAll(".shelf3d").length'));
console.log('第一本尺寸: ' + await evalJs(c, '(function(){var b=document.querySelector(".shelf3d-scene");var r=b.getBoundingClientRect();return Math.round(r.width)+"x"+Math.round(r.height)})()'));
console.log('封面结构: ' + await evalJs(c, '(function(){var v=document.querySelector(".shelf3d-cover");return v?JSON.stringify({index:!!v.querySelector(".sb-index"),prov:!!v.querySelector(".sb-prov"),photo:!!v.querySelector(".sb-photo"),meta:!!v.querySelector(".sb-meta")}):"无"})()'));
console.log('省份名字号: ' + await evalJs(c, '(function(){var v=document.querySelector(".sb-prov");return v?getComputedStyle(v).fontSize:"无"})()'));
// 悬停第一本
const pt = JSON.parse(await evalJs(c, '(function(){var b=document.querySelector(".shelf3d");var r=b.getBoundingClientRect();return JSON.stringify({x:Math.round(r.left+r.width/2),y:Math.round(r.top+r.height*0.4)})})()'));
await c.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: pt.x, y: pt.y, button: 'none' });
await sleep(1200);
const { data } = await c.send('Page.captureScreenshot', { format: 'png', clip: { x: 120, y: 120, width: 1200, height: 800, scale: 1 } });
const fs = await import('node:fs/promises');
await fs.writeFile('B:/dell/Documents/harness/shots/my-shelf-new.png', Buffer.from(data, 'base64'));
console.log('截图: shots/my-shelf-new.png');
ws2.close(); await closeTab(t.id);
