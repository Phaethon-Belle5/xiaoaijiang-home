await new Promise(r => ws2.addEventListener('open', r));
const errs = [];
ws2.addEventListener('message', ev => { try { const m = JSON.parse(ev.data);
  if (m.method === 'Runtime.consoleAPICalled' && (m.params.type==='error'||m.params.type==='warning')) errs.push((m.params.args||[]).map(a=>a.value||'').join(' ').slice(0,160));
  if (m.method === 'Runtime.exceptionThrown') { const d = m.params.exceptionDetails; errs.push('[throw] ' + String(d.exception&&d.exception.description||d.text).split('\n')[0].slice(0,160)); }
} catch (e) {} });
ws2.send(JSON.stringify({ id: 1, method: 'Runtime.enable' }));
