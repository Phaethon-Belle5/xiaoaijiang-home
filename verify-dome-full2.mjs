import { openTab, connect, closeTab, sleep, evalJs } from './cdp-client.mjs';
const t = await openTab('about:blank');
const c = await connect(t.ws);
const ws2 = new WebSocket(t.ws);
await new Promise(r => ws2.addEventListener('open', r));
ws2.send(JSON.stringify({ id: 1, method: 'Runtime.enable' }));
await c.send('Network.enable');
await c.send('Network.setCacheDisabled', { cacheDisabled: true });
await c.send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 950, deviceScaleFactor: 1.5, mobile: false });
await c.send('Page.navigate', { url: 'https://map.231060101.xyz/?f3=' + Date.now() });
await sleep(12000);
await evalJs(c, "(function(){var l=document.getElementById('launch');if(l)l.remove();return 0})()");
await sleep(700);
await evalJs(c, "openMemPop('images'), 1");
await sleep(4000);
console.log('按钮: ' + await evalJs(c, 'JSON.stringify([].slice.call(document.querySelectorAll(".ti-actions button")).map(function(b){return b.textContent.trim()}))'));
await evalJs(c, 'memDomeFull(), 1');
await sleep(2500);
const st = JSON.parse(await evalJs(c, `(function(){var d=document.querySelector('.life-photo-dome.dome-fullscreen');var r=d?d.getBoundingClientRect():null;
  return JSON.stringify({全屏类:!!d, 尺寸:r?Math.round(r.width)+'x'+Math.round(r.height):'-', 返回按钮:!!document.querySelector('.dome-full-close')})})()`));
console.log('全屏: ' + JSON.stringify(st));
const { data } = await c.send('Page.captureScreenshot', { format: 'png' });
const fs = await import('node:fs/promises');
await fs.writeFile('B:/dell/Documents/harness/shots/dome-full.png', Buffer.from(data, 'base64'));
await evalJs(c, 'memDomeExit(), 1');
await sleep(1200);
console.log('退出后: ' + await evalJs(c, '(function(){return document.querySelectorAll(".life-photo-dome.dome-fullscreen").length+" 个还在全屏 / 穹顶仍在页内: "+!!document.querySelector("#memPanel .life-photo-dome")})()'));
console.log('  截图: shots/dome-full.png');
ws2.close(); await closeTab(t.id);
